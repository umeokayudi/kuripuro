/** Smart Facility — tabelas do modelo digital por restaurante e recomendações de serviço. */
export const FACILITY_STATEMENTS = [
  `create table if not exists facility_models (
    id uuid primary key default gen_random_uuid(),
    client_id uuid references clients(id) on delete cascade not null,
    location_name text,
    name text not null,
    layout jsonb not null default '{}'::jsonb,
    photos jsonb not null default '[]'::jsonb,
    status text not null default 'draft' check (status in ('draft', 'approved')),
    ai_notes text,
    approved_at timestamptz,
    created_at timestamptz default now(),
    updated_at timestamptz default now()
  )`,
  `create table if not exists facility_recommendations (
    id uuid primary key default gen_random_uuid(),
    model_id uuid references facility_models(id) on delete cascade not null,
    client_id uuid references clients(id) on delete cascade not null,
    location_name text,
    element_id text,
    element_name text,
    service text not null,
    reason text,
    priority text not null default 'medium' check (priority in ('high', 'medium', 'low')),
    source text not null default 'rule' check (source in ('ai', 'rule', 'admin')),
    status text not null default 'pending' check (status in ('pending', 'accepted', 'declined', 'done')),
    decided_by text,
    decided_at timestamptz,
    client_request_id uuid,
    created_at timestamptz default now()
  )`,
  `create table if not exists facility_service_log (
    id uuid primary key default gen_random_uuid(),
    model_id uuid references facility_models(id) on delete cascade not null,
    client_id uuid references clients(id) on delete cascade not null,
    location_name text,
    element_id text not null,
    element_name text,
    service text,
    service_date date not null default ((now() at time zone 'Asia/Tokyo')::date),
    job_id uuid references jobs(id) on delete set null,
    employee_id uuid,
    employee_name text,
    notes text,
    photos jsonb not null default '[]'::jsonb,
    created_at timestamptz default now()
  )`,
  `alter table facility_models enable row level security`,
  `alter table facility_service_log enable row level security`,
  `drop policy if exists "allow_all_facility_service_log" on facility_service_log`,
  `create policy "allow_all_facility_service_log" on facility_service_log for all using (true)`,
  `create index if not exists idx_facility_log_model on facility_service_log(model_id, element_id, service_date desc)`,
  `create index if not exists idx_facility_log_job on facility_service_log(job_id)`,
  `alter table facility_recommendations enable row level security`,
  `drop policy if exists "allow_all_facility_models" on facility_models`,
  `create policy "allow_all_facility_models" on facility_models for all using (true)`,
  `drop policy if exists "allow_all_facility_recommendations" on facility_recommendations`,
  `create policy "allow_all_facility_recommendations" on facility_recommendations for all using (true)`,
  `create index if not exists idx_facility_models_client on facility_models(client_id, location_name)`,
  `create index if not exists idx_facility_recs_model on facility_recommendations(model_id, status, created_at desc)`,
  `create index if not exists idx_facility_recs_client on facility_recommendations(client_id, status)`,
]

export const FACILITY_SETUP_SQL = `-- KuriPuro Smart Facility — cole tudo e clique RUN\n${FACILITY_STATEMENTS.map(s => s.replace(/\n {4}/g, '\n  ').replace(/\n {2}\)$/, '\n)') + ';').join('\n\n')}\n`
