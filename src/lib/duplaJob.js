// v1.0.197 · "Serviço em dupla": two employees do the same service together.
// The person who joins (helper) gets their OWN job row for the same store/day — so salary, Live Track,
// photos, checklist and signature keep working per person with no new table — and the worker's pay of
// the service is split 50/50 between the two rows. The link lives in one line of each description:
//   main:   "👥 Dupla com Gabriel · job <helper job id>"
//   helper: "👥 Ajudando Guilherme · job <main job id>"
// The helper row has no client_id, so billing / client portal / per-visit counts see one visit only.
// Pure rules here (node-testable); database + storage writes live in duplaJobOps.js.
import { jobEmployeePay, stripPayText } from './jobEmployeePay.js'

export const DUPLA_MAIN_TAG = '👥 Dupla com'
export const DUPLA_HELPER_TAG = '👥 Ajudando'
export const DUPLA_LEFT_TAG = '👥 Dupla desfeita'
const UUID = '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}'
const MAIN_RE = new RegExp(`👥 Dupla com (.+?) · job (${UUID})`, 'i')
const HELPER_RE = new RegExp(`👥 Ajudando (.+?) · job (${UUID})`, 'i')
const LEFT_RE = new RegExp(`👥 Dupla desfeita[^\\n]*?· job (${UUID})`, 'gi')

export const duplaLine = (role, partnerName, partnerJobId) =>
  `${role === 'helper' ? DUPLA_HELPER_TAG : DUPLA_MAIN_TAG} ${String(partnerName || '—').replace(/·/g, '-').trim()} · job ${partnerJobId}`

/** { role: 'main' | 'helper', partnerName, partnerJobId } or null when the job is not in a pair. */
export function duplaInfo(job) {
  const d = String(job?.description || '')
  if (!d.includes('👥')) return null
  const undone = new Set([...d.matchAll(LEFT_RE)].map(m => m[1].toLowerCase()))
  let found = null
  for (const line of d.split('\n')) {
    const h = line.match(HELPER_RE)
    const m = h ? null : line.match(MAIN_RE)
    const hit = h || m
    if (!hit || undone.has(hit[2].toLowerCase())) continue
    found = { role: h ? 'helper' : 'main', partnerName: hit[1].trim(), partnerJobId: hit[2] }
  }
  return found
}

export const isDupla = job => !!duplaInfo(job)
export const isDuplaHelper = job => duplaInfo(job)?.role === 'helper'

/** Are a and b the two halves of the same pair? */
export function areDuplaPartners(a, b) {
  if (!a || !b) return false
  const ia = duplaInfo(a), ib = duplaInfo(b)
  return (ia?.partnerJobId === b.id) || (ib?.partnerJobId === a.id)
}

/** Whole yen split in two: the person who already had the service keeps the odd yen. */
export function splitHalf(amount) {
  if (amount === null || amount === undefined || amount === '') return [null, null]
  const n = Math.round(Number(amount))
  if (!Number.isFinite(n) || n < 0) return [null, null]
  const helper = Math.floor(n / 2)
  return [n - helper, helper]
}

/**
 * Can `helperId` join `main` as a pair today?
 * error: 'not_found' | 'own_job' | 'already_dupla' | 'not_open' | 'not_today' | 'no_person'
 */
export function canJoinDupla(main, helperId, today) {
  if (!main?.id) return { ok: false, error: 'not_found' }
  if (!main.employee_id) return { ok: false, error: 'no_person' }
  if (main.employee_id === helperId) return { ok: false, error: 'own_job' }
  if (isDupla(main)) return { ok: false, error: 'already_dupla' }
  if (!['assigned', 'in_progress'].includes(main.status)) return { ok: false, error: 'not_open' }
  if (today && main.scheduled_date !== today) return { ok: false, error: 'not_today' }
  return { ok: true }
}

const withLine = (desc, line) => [String(desc || '').trim(), line].filter(Boolean).join('\n')

/**
 * Everything the join writes, without touching the database.
 * main: the running (or planned) job of the other person, read with employee_pay + spot_value.
 * helper: { id, name }.
 * Returns { mainPatch, helperRow, split } — helperRow.id is generated by the caller (crypto.randomUUID)
 * so both description lines can point at each other in one go.
 */
export function buildDuplaPlan(main, helper, { helperJobId, now = new Date().toISOString(), sequenceOrder = null } = {}) {
  const originalPay = jobEmployeePay(main)
  const [mainPay, helperPay] = splitHalf(originalPay)
  const isSpot = main.job_category === 'spot'
  const originalSpot = isSpot && main.spot_value !== null && main.spot_value !== undefined ? Number(main.spot_value) : null
  const [mainSpot, helperSpot] = splitHalf(originalSpot)
  const running = main.status === 'in_progress' || !!main.started_at

  const mainPatch = {
    description: withLine(main.description, duplaLine('main', helper.name, helperJobId)),
    ...(originalPay !== null ? { employee_pay: mainPay } : {}),
    ...(originalSpot !== null ? { spot_value: mainSpot } : {}),
  }
  const helperRow = {
    id: helperJobId,
    title: main.title,
    client_id: null, // billing and the client portal count the visit once (on the main job)
    client_name: main.client_name || null,
    employee_id: helper.id,
    employee_name: helper.name,
    scheduled_date: main.scheduled_date,
    scheduled_time: main.scheduled_time || null,
    address: main.address || '',
    gps_lat: main.gps_lat ?? null,
    gps_lng: main.gps_lng ?? null,
    description: withLine(stripPayText(main.description), duplaLine('helper', main.employee_name, main.id)),
    checklist_template: main.checklist_template || null,
    photo_required: !!main.photo_required,
    status: running ? 'in_progress' : 'assigned',
    started_at: running ? now : null,
    job_category: main.job_category || 'regular',
    ...(isSpot ? { spot_status: 'accepted', spot_value: helperSpot } : {}),
    counts_as_work_day: main.counts_as_work_day ?? true,
    materials: main.materials || null,
    reference_photos: main.reference_photos || null,
    instructions: main.instructions || null,
    area: main.area || null,
    value: 0, // the client price stays only on the main job
    employee_pay: helperPay,
    ...(sequenceOrder ? { sequence_order: sequenceOrder } : {}),
  }
  return {
    mainPatch,
    helperRow,
    split: { originalPay, mainPay, helperPay, originalSpot, mainSpot, helperSpot, at: now },
  }
}

/** Patches that undo a pair: the main job gets its whole pay back, the helper row is cancelled. */
export function undoDuplaPlan(main, helperJob, audit, { by = '', now = new Date().toISOString() } = {}) {
  const stamp = now.slice(0, 16).replace('T', ' ')
  const left = `${DUPLA_LEFT_TAG} (${by || '—'}) em ${stamp} · job ${helperJob?.id || audit?.helper_job_id || ''}`
  const mainPatch = {
    description: withLine(main?.description, left),
    ...(audit?.split?.originalPay !== null && audit?.split?.originalPay !== undefined ? { employee_pay: audit.split.originalPay } : {}),
    ...(audit?.split?.originalSpot !== null && audit?.split?.originalSpot !== undefined ? { spot_value: audit.split.originalSpot } : {}),
  }
  const leftHelper = `${DUPLA_LEFT_TAG} (${by || '—'}) em ${stamp} · job ${main?.id || ''}`
  const helperPatch = helperJob ? { status: 'cancelled', description: withLine(helperJob.description, leftHelper) } : null
  return { mainPatch, helperPatch }
}

/** What each person did, for the service report: done / not done checklist items + note + times. */
export function memberWork(job, checklistRows = []) {
  return {
    job_id: job?.id || null,
    name: job?.employee_name || '',
    started_at: job?.started_at || null,
    completed_at: job?.completed_at || null,
    status: job?.status || '',
    done: (checklistRows || []).filter(r => r.done).map(r => r.label),
    not_done: (checklistRows || []).filter(r => !r.done).map(r => r.label),
    note: String(job?.notes_employee || '').trim(),
    sig: null,
  }
}
